/*DELIVERY ANALYSIS*/
--Average Delivery Time
SELECT
AVG(DATEDIFF(day,
order_purchase_timestamp,
order_delivered_customer_date))
AS Avg_Delivery_Days
FROM orders
WHERE order_status='delivered';
GO

Insight:Average delivery time reflects the overall efficiency of the logistics network

--Fastest Delivered Orders
SELECT TOP 10
order_id,
DATEDIFF(day,
order_purchase_timestamp,
order_delivered_customer_date)
AS Delivery_Days
FROM orders
WHERE order_status='delivered'
ORDER BY Delivery_Days;
GO

Insight:Fast deliveries improve customer satisfaction and enhance the shopping experience

--Delayed Deliveries
SELECT TOP 10
order_id,
DATEDIFF(day,
order_estimated_delivery_date,
order_delivered_customer_date)
AS Delay_Days
FROM orders
WHERE order_delivered_customer_date >
order_estimated_delivery_date
ORDER BY Delay_Days DESC;
GO	

Insight:Delayed deliveries may negatively impact customer satisfaction and review scores

--Delivery time By State
SELECT
c.customer_state,
AVG(DATEDIFF(day,
o.order_purchase_timestamp,
o.order_delivered_customer_date))
AS Avg_Delivery_Days
FROM customers c
JOIN orders o
ON c.customer_id=o.customer_id
WHERE o.order_status='delivered'
GROUP BY c.customer_state
ORDER BY Avg_Delivery_Days DESC;
GO

Insight:Delivery performance varies by state, highlighting regions that may require logistics improvements


