GO

Insight:Categorizing deliveries into Fast, Normal, and Delayed simplifies logistics performance monitoring

--Monthly SaLes View
CREATE VIEW Monthly_Sales AS
SELECT
YEAR(o.order_purchase_timestamp) AS Sales_Year,
MONTH(o.order_purchase_timestamp) AS Sales_Month,
SUM(op.payment_value) AS Revenue
FROM orders o
JOIN order_payments op
ON o.order_id=op.order_id
GROUP BY
YEAR(o.order_purchase_timestamp),
MONTH(o.order_purchase_timestamp);
GO

Insight:The monthly sales summary provides a consolidated view of revenue trends over time

--Running Revenue Trend
SELECT
Sales_Year,
Sales_Month,
Revenue,
SUM(Revenue) OVER(
ORDER BY Sales_Year, Sales_Month
) AS Running_Revenue
FROM Monthly_Sales;
GO

Insight:Running revenue highlights cumulative business growth and long-term sales performance
