--Delivery Performance Classification
SELECT
order_id,
DATEDIFF(day,
order_purchase_timestamp,
order_delivered_customer_date)
AS Delivery_Days,
CASE
WHEN DATEDIFF(day,
order_purchase_timestamp,
order_delivered_customer_date) <=3
THEN 'Fast'

WHEN DATEDIFF(day,
order_purchase_timestamp,
order_delivered_customer_date) <=7
