/*REVIEW ANALYSIS*/
--Average Review Score
SELECT
AVG(CAST(review_score AS FLOAT))
AS Average_Rating
FROM order_reviews;
GO

--Different Categories With Lowest Average Ratings
SELECT TOP 10
p.product_category_name,
AVG(CAST(r.review_score AS FLOAT)) AS Avg_Rating
FROM products p
JOIN order_items oi
ON p.product_id=oi.product_id
JOIN order_reviews r
ON oi.order_id=r.order_id
GROUP BY p.product_category_name
ORDER BY Avg_Rating ASC;
GO

--Sellers Above Average Revenue(CTE)
WITH SellerRevenue AS
(
    SELECT
        seller_id,
        SUM(price) AS Revenue
    FROM order_items
    GROUP BY seller_id
)

SELECT *
FROM SellerRevenue
WHERE Revenue >
(
    SELECT AVG(Revenue)
    FROM SellerRevenue
	);
GO

Insight:Sellers exceeding the average revenue represent the marketplaces top-performing businesses.

